    val onOpenIntervalTime: () -> Unit,
    val onConfirmInterval: () -> Unit,
    val onDismissInterval: () -> Unit,
    val onClearReminder: () -> Unit,
    val onSave: () -> Unit,
    val onBack: () -> Unit,
    val onConfirmDiscard: () -> Unit,
    val onDismissDiscard: () -> Unit,
)

